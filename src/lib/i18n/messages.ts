export const dictionaries: Record<Lang, Record<MsgKey, string>> = { en, hi };
export const LANG_COOKIE = "lang";

export function isMsgKey(k: string): k is MsgKey {
  return Object.prototype.hasOwnProperty.call(en, k);
}

/** Translate a key (or pass through any non-key text, e.g. Zod's default English messages). */
export function translate(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = isMsgKey(key) ? dictionaries[lang][key] : key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
